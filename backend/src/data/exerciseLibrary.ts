// FitLingo exercise library — the single curated catalog the AI plan generator
// composes from. Every exercise has a STABLE id (slug); media and demo visuals
// on the frontend are keyed by this id. The first 21 entries are the original
// catalog and their `en.name` values must stay byte-identical to the legacy
// names (old mission snapshots in the DB and media maps match on them).
//
// The frontend keeps a copy at frontend/src/data/exerciseLibrary.ts for demo
// mode — after editing this file run `npm run sync:library` in frontend/.

export type ExerciseCategory =
  | 'warmup'
  | 'legs_glutes'
  | 'core'
  | 'upper_body'
  | 'cardio'
  | 'full_body'
  | 'mobility'
  | 'balance';

export type ExerciseDifficulty = 'beginner' | 'intermediate' | 'advanced';

export type ExerciseDose = {
  type: 'time' | 'reps';
  amount: number; // seconds for 'time', repetitions for 'reps'
  perSide?: boolean;
};

export type ExerciseText = {
  name: string;
  instructions: string;
  safetyNote: string;
  target: string;
  alternative: string;
  instructorCue: string;
};

export type LibraryExercise = {
  id: string;
  category: ExerciseCategory;
  difficulty: ExerciseDifficulty;
  // Values match the onboarding equipment options; [] = no equipment needed.
  equipment: string[];
  musclesWorked: string[];
  defaultDose: ExerciseDose;
  en: ExerciseText;
  he: ExerciseText;
};

// The legacy Exercise shape used across missions/path snapshots, plus exerciseId.
export type ResolvedExercise = {
  exerciseId: string;
  name: string;
  duration: string;
  instructions: string;
  safetyNote: string;
  target: string;
  alternative: string;
  mediaType?: 'gif' | 'video' | 'image' | 'none';
  mediaUrl?: string;
  mediaCredit?: string;
  instructorCue?: string;
  musclesWorked?: string[];
};

export type ExerciseLanguage = 'en' | 'he';

const DEFAULT_SAFETY_EN = 'Move with control and keep the range pain-free.';
const DEFAULT_SAFETY_HE = 'נועו בשליטה ושמרו על טווח תנועה ללא כאב.';

const t = (amount: number, perSide = false): ExerciseDose => ({ type: 'time', amount, perSide });
const r = (amount: number, perSide = false): ExerciseDose => ({ type: 'reps', amount, perSide });

// Tuple order: [name, instructions, target, alternative, instructorCue]
const ex = (
  id: string,
  category: ExerciseCategory,
  difficulty: ExerciseDifficulty,
  equipment: string[],
  musclesWorked: string[],
  defaultDose: ExerciseDose,
  en: [string, string, string, string, string],
  he: [string, string, string, string, string],
  safety?: [string, string]
): LibraryExercise => ({
  id,
  category,
  difficulty,
  equipment,
  musclesWorked,
  defaultDose,
  en: { name: en[0], instructions: en[1], target: en[2], alternative: en[3], instructorCue: en[4], safetyNote: safety?.[0] ?? DEFAULT_SAFETY_EN },
  he: { name: he[0], instructions: he[1], target: he[2], alternative: he[3], instructorCue: he[4], safetyNote: safety?.[1] ?? DEFAULT_SAFETY_HE },
});


export const exerciseById: Map<string, LibraryExercise> = new Map(
  exerciseLibrary.map((entry) => [entry.id, entry])
);

export const formatDose = (dose: ExerciseDose, lang: ExerciseLanguage): string => {
  // Digits always lead the string so the frontend timer (getExerciseSeconds)
  // can parse the leading number in both languages.
  if (lang === 'he') {
    const unit = dose.type === 'time' ? 'שניות' : 'חזרות';
    return dose.perSide ? `${dose.amount} ${unit} לכל צד` : `${dose.amount} ${unit}`;
  }
  const unit = dose.type === 'time' ? 'seconds' : 'reps';
  return dose.perSide ? `${dose.amount} ${unit} each side` : `${dose.amount} ${unit}`;
};

export const resolveExercise = (
  id: string,
  lang: ExerciseLanguage = 'en',
  dose?: ExerciseDose
): ResolvedExercise => {
  const entry = exerciseById.get(id);
  if (!entry) {
    throw new Error(`Unknown exercise id: ${id}`);
  }
  const text = lang === 'he' ? entry.he : entry.en;
  return {
    exerciseId: entry.id,
    name: text.name,
    duration: formatDose(dose ?? entry.defaultDose, lang),
    instructions: text.instructions,
    safetyNote: text.safetyNote,
    target: text.target,
    alternative: text.alternative,
    mediaType: 'none',
    mediaUrl: '',
    instructorCue: text.instructorCue,
    musclesWorked: entry.musclesWorked,
  };
};

const LanguageContext = createContext<LanguageContextValue | undefined>(undefined);

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => (localStorage.getItem('language') as Language) || 'en');

  const setLanguage = (nextLanguage: Language) => {
    localStorage.setItem('language', nextLanguage);
    setLanguageState(nextLanguage);
  };

  useEffect(() => {
    document.documentElement.lang = language;
    document.documentElement.dir = language === 'he' ? 'rtl' : 'ltr';
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    isHebrew: language === 'he',
    setLanguage,
    t: (key: string) => dictionary[language][key] || dictionary.en[key] || key,
    tv: (text: string) => (language === 'he' ? valueTranslations[text] || text : text),
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used inside LanguageProvider');
  }
  return context;
};

export const formatText = (template: string, values: Record<string, string | number>) => (
  Object.entries(values).reduce((text, [key, value]) => text.replace(`{${key}}`, String(value)), template)
);
